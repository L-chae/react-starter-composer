const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '../..');
const BACKEND_ROOT = path.resolve(__dirname, '..');
const OUTPUT_ROOT = path.resolve(BACKEND_ROOT, 'output/temp');

function toPosixPath(value) {
  return value.replace(/\\/g, '/');
}

function ensureWithin(parentDir, targetPath, label) {
  const relative = path.relative(parentDir, targetPath);
  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error(label + ' is outside allowed directory: ' + targetPath);
  }
}

function resolveDestinationPath(sourceFile, language) {
  const normalized = toPosixPath(sourceFile);
  const basePrefix = `templates/base/${language}/`;
  const optionsPrefix = 'templates/options/';

  if (normalized.startsWith(basePrefix)) {
    return normalized.slice(basePrefix.length);
  }

  if (normalized.startsWith(optionsPrefix)) {
    const remainder = normalized.slice(optionsPrefix.length);
    const parts = remainder.split('/');
    const optionId = parts[0];
    const maybeLanguage = parts[1];

    if (!optionId) {
      throw new Error('Invalid option file path: ' + sourceFile);
    }

    if (maybeLanguage === language) {
      return parts.slice(2).join('/');
    }

    return parts.slice(1).join('/');
  }

  throw new Error('Unsupported template file path: ' + sourceFile);
}

function mergePackageJson(basePackageJson, composerResult) {
  const merged = { ...basePackageJson };

  const mergedDependencies = { ...(basePackageJson.dependencies || {}) };
  const mergedDevDependencies = { ...(basePackageJson.devDependencies || {}) };

  for (const name of composerResult.dependencies || []) {
    if (!mergedDependencies[name]) {
      mergedDependencies[name] = '*';
    }
  }

  for (const name of composerResult.devDependencies || []) {
    if (!mergedDevDependencies[name]) {
      mergedDevDependencies[name] = '*';
    }
  }

  merged.dependencies = mergedDependencies;
  merged.devDependencies = mergedDevDependencies;
  merged.scripts = {
    ...(basePackageJson.scripts || {}),
    ...(composerResult.scripts || {}),
  };

  return merged;
}

function buildProjectReadme(composerResult) {
  const selectedOptions = composerResult.selectedOptions || [];
  const optionsLine = selectedOptions.length > 0 ? selectedOptions.join(', ') : '(none)';
  const installCommands = composerResult.installCommands || ['npm install'];

  return [
    '# ' + composerResult.projectName,
    '',
    'Generated by React Starter Composer.',
    '',
    '## Configuration',
    '- Language: ' + composerResult.language,
    '- Selected options: ' + optionsLine,
    '',
    '## Install',
    '```bash',
    ...installCommands,
    '```',
    '',
    '## Run',
    '```bash',
    'npm run dev',
    '```',
    '',
  ].join('\n');
}

function generateProjectFromComposerResult(composerResult) {
  if (!composerResult || typeof composerResult !== 'object') {
    throw new Error('composerResult must be an object.');
  }

  const { projectName, language, files } = composerResult;

  if (!projectName || typeof projectName !== 'string') {
    throw new Error('composerResult.projectName is required.');
  }

  if (!['js', 'ts'].includes(language)) {
    throw new Error('composerResult.language must be js or ts.');
  }

  if (!Array.isArray(files) || files.length === 0) {
    throw new Error('composerResult.files must be a non-empty array.');
  }

  const projectDir = path.resolve(OUTPUT_ROOT, projectName);
  ensureWithin(OUTPUT_ROOT, projectDir, 'Project directory');

  fs.mkdirSync(OUTPUT_ROOT, { recursive: true });
  fs.rmSync(projectDir, {
    recursive: true,
    force: true,
    maxRetries: 5,
    retryDelay: 100,
  });
  fs.mkdirSync(projectDir, { recursive: true });

  const generatedFiles = [];

  for (const sourceFile of files) {
    const sourcePath = path.resolve(REPO_ROOT, sourceFile);

    if (!fs.existsSync(sourcePath)) {
      throw new Error('Template source file not found: ' + sourceFile);
    }

    const relativeDestination = resolveDestinationPath(sourceFile, language);
    const destinationPath = path.resolve(projectDir, relativeDestination);
    ensureWithin(projectDir, destinationPath, 'Destination file');

    fs.mkdirSync(path.dirname(destinationPath), { recursive: true });
    fs.copyFileSync(sourcePath, destinationPath);
    generatedFiles.push(toPosixPath(relativeDestination));
  }

  const packageJsonPath = path.resolve(projectDir, 'package.json');
  const basePackageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
  const mergedPackageJson = mergePackageJson(basePackageJson, composerResult);

  fs.writeFileSync(packageJsonPath, JSON.stringify(mergedPackageJson, null, 2) + '\n', 'utf8');
  generatedFiles.push('package.json');

  const readmePath = path.resolve(projectDir, 'README.md');
  fs.writeFileSync(readmePath, buildProjectReadme(composerResult), 'utf8');
  generatedFiles.push('README.md');

  const uniqueSortedFiles = [...new Set(generatedFiles)].sort();

  return {
    outputPath: projectDir,
    generatedFiles: uniqueSortedFiles,
  };
}

module.exports = {
  generateProjectFromComposerResult,
};
